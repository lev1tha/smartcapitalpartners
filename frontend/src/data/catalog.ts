export function getOps(id: string): ModelOps | undefined {
  return modelOps[id]
}

export function getModel(id: string): BusinessModel | undefined {
  return businessModels.find((m) => m.id === id)
}

export function relatedModels(model: BusinessModel, limit = 3): BusinessModel[] {
  return businessModels
    .filter((m) => m.id !== model.id && m.sphere === model.sphere)
    .slice(0, limit)
}

